/**
 * The visual editor (T-029 C2, C3; ADR 0028): the screen's component tree, a property form for the
 * selected node generated by [FormSchema], and the palette's structural edits ([Palette]). Every
 * change is checked as a whole screen and saved as the same draft the JSON editor shows; `?node=`
 * is the selection (a component, `""` for the screen, or a list such as `components.2.empty`).
 */
internal fun Route.visualPages(screens: ScreenStore, probe: ApiProbe, publishing: ScreenPublishing) {
    val dataFields = DataFields(probe)
    route("/screens/{id}/visual") {
        get {
            val editing = call.editing(screens) ?: return@get
            val node = call.request.queryParameters["node"].orEmpty()
            if (!editing.exists(node)) return@get call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val saved = "saved" in call.request.queryParameters
            val notice = if (saved) "Saved as a draft. Apps still get the live version." else ""
            call.visualPage(screens, editing, node, editing.values(node)::get, emptyList(), notice)
        }
        post {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            val fields =
                editing.fields(node)
                    ?: return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val params = call.receiveParameters()
            val problems = mutableListOf<String>()
            val parsed = FormSchema.parse(fields, params::get, problems)
            if (node == Editing.NEW_VALUE || node == Editing.NEW_SOURCE) {
                val isValue = node == Editing.NEW_VALUE
                val section = if (isValue) "values" else "data"
                val kind = if (isValue) "screen value" else "data source"
                val name = params["__name"].orEmpty().trim()
                val existing = editing.root[section] as? JsonObject ?: JsonObject(emptyMap())
                if (!NEW_ENTRY_NAME.matches(name)) {
                    problems += "name: use letters, digits and _ (starting with a letter)"
                } else if (name in existing) {
                    problems += "name: there is already a $kind '$name'"
                }
                val updated = if (problems.isEmpty()) {
                    JsonObject(editing.root + (section to JsonObject(existing + (name to parsed))))
                } else {
                    editing.root
                }
                call.saveOrShow(screens, publishing, editing, updated, "", problems) { params[it] }
                return@post
            }
            val screen = ScreenTree.set(editing.root, node, editing.rebuild(node, parsed))
            call.saveOrShow(screens, publishing, editing, screen, node, problems) { params[it] }
        }
        // C3: add, delete, duplicate, move, nest, wrap — form fields `op` and `type`.
        post("/edit") {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            if (!editing.exists(node)) return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val params = call.receiveParameters()
            val type = params["type"].orEmpty()
            val root = editing.root
            val result = try {
                when (params["op"]) {
                    "add-after" -> requireNotNull(Palette.location(node)) { "select a component first" }
                        .let { (list, index) -> Palette.add(root, list, index + 1, type) }
                    "add-inside" -> Palette.add(
                        root,
                        "$node.${requireNotNull(Palette.firstList(root, node)) {
                            "not a container"
                        }}",
                        null,
                        type,
                    )
                    "add-end" -> Palette.add(root, node.ifEmpty { "components" }, null, type)
                    "up" -> Palette.move(root, node, -1)
                    "down" -> Palette.move(root, node, 1)
                    "into-previous" -> Palette.intoPrevious(root, node)
                    "out" -> Palette.outOfParent(root, node)
                    "duplicate" -> Palette.duplicate(root, node)
                    "delete" -> Palette.delete(root, node)
                    "wrap" -> Palette.wrap(root, node, type)
                    "move-to" -> Palette.moveTo(
                        root,
                        params["from"].orEmpty().ifEmpty { node },
                        params["target"].orEmpty(),
                        params["position"].orEmpty(),
                    )
                    "add-source" -> Palette.addSource(root, params["name"].orEmpty(), params["url"].orEmpty())
                    "delete-source" -> Palette.deleteSource(root, node)
                    "add-value" -> Palette.addValue(
                        root,
                        params["name"].orEmpty(),
                        params["default"].orEmpty(),
                        params["min"].orEmpty(),
                        params["max"].orEmpty(),
                    )
                    "delete-value" -> Palette.deleteValue(root, node)
                    else -> throw IllegalArgumentException("unknown operation '${params["op"]}'")
                }
            } catch (e: IllegalArgumentException) {
                call.response.status(HttpStatusCode.UnprocessableEntity)
                return@post call.visualPage(
                    screens,
                    editing,
                    node,
                    editing.values(node)::get,
                    listOf(e.message ?: "not possible"),
                    "",
                )
            }
            call.saveOrShow(screens, publishing, editing, result.screen, result.select, emptyList()) {
                editing.values(node)[it]
            }
        }
        // T-031 W3, HTMX: the field picker — bindings usable at the node, with samples from the real data.
        get("/fields") {
            val editing = call.editing(screens) ?: return@get
            val node = call.request.queryParameters["node"].orEmpty()
            if (!editing.exists(node)) return@get call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val groups = dataFields.groups(editing.root, node)
            call.respondTemplate(
                "admin/_fields.ftl",
                mapOf(
                    "groups" to groups.map { g ->
                        mapOf(
                            "title" to g.title,
                            "error" to g.error.orEmpty(),
                            "fields" to g.fields.map { mapOf("binding" to it.binding, "sample" to it.sample) },
                        )
                    },
                ),
            )
        }
        // HTMX: re-render the form from what is typed (e.g. another action type picked); saves nothing.
        post("/panel") {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            val fields =
                editing.fields(node)
                    ?: return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val params = call.receiveParameters()
            val screenValues = (editing.root["values"] as? JsonObject)?.keys?.toList().orEmpty()
            val visibilityIds = collectVisibilityIds(editing.root)
            call.respondTemplate(
                "admin/_form.ftl",
                mapOf(
                    "rows" to formRows(fields, params::get, screenValues, visibilityIds),
                    "canEdit" to true,
                    "panelUrl" to call.panelUrl(node),
                ),
            )
        }
    }
}

/**
 * Saves [screen] as the draft when it is valid and keeps its id, then selects [select]; otherwise
 * shows the page again (at the old selection, with [value] in the form) with every problem.
 */
private suspend fun ApplicationCall.saveOrShow(
    screens: ScreenStore,
    publishing: ScreenPublishing,
    editing: Editing,
    screen: JsonObject,
    select: String,
    problems: List<String>,
    value: (String) -> String?,
) {
    val checked = ScreenJson.check(screen.toString())
    val valid = checked.screen
    val all = problems + checked.problems +
        listOfNotNull("id: must stay '${editing.stored.id}'".takeIf { valid != null && valid.id != editing.stored.id })
    val node = request.queryParameters["node"].orEmpty()
    if (all.isNotEmpty() || valid == null) {
        response.status(HttpStatusCode.UnprocessableEntity)
        return visualPage(screens, editing, node, value, all, "")
    }
    val saved = ScreenJson.encode(valid)
    screens.saveDraft(editing.stored.id, saved)
    publishing.updatePreview(saved, adminUser.previewOwner) // T-032: an open phone shows the edit
    seeOther("/admin/screens/${editing.stored.id.urlEncoded()}/visual?node=${select.urlEncoded()}&saved")
}

/** The screen being edited: the draft if there is one, else the live version. */
internal class Editing(
    val stored: ScreenStore.StoredScreen,
    val json: String = stored.draftJson ?: stored.liveJson.orEmpty(),
) {
    val root: JsonObject = Json.parseToJsonElement(json) as JsonObject

    fun node(path: String): JsonObject? = ScreenTree.get(root, path) as? JsonObject

    private fun type(path: String) = (node(path)?.get("type") as? JsonPrimitive)?.content

    /** A data source node `data.<name>` (T-031 W3). */
    fun isSource(path: String) = path != NEW_SOURCE && path.startsWith("data.") && path.count { it == '.' } == 1

    /** An on-device screen value node `values.<name>`. */
    fun isValue(path: String) = path != NEW_VALUE && path.startsWith("values.") && path.count { it == '.' } == 1

    /** A component list path (`components`, `components.2.empty`): its last segment is a name. */
    fun isList(path: String) = path != "data" && path != NEW_SOURCE && !isSource(path) &&
        path != "values" && path != NEW_VALUE && !isValue(path) &&
        path.isNotEmpty() && path.substringAfterLast('.').toIntOrNull() == null

    /** The selection exists: the screen, a component, or a component list of the screen or a component. */
    fun exists(path: String): Boolean = when {
        path.isEmpty() || path == "data" || path == "values" || path == NEW_SOURCE || path == NEW_VALUE -> true
        isSource(path) -> (root["data"] as? JsonObject)?.containsKey(path.removePrefix("data.")) == true
        isValue(path) -> (root["values"] as? JsonObject)?.containsKey(path.removePrefix("values.")) == true
        isList(path) -> {
            val owner = if ('.' in path) path.substringBeforeLast('.') else ""
            val name = path.substringAfterLast('.')
            if (owner.isEmpty()) {
                name in setOf("components", "error")
            } else {
                Palette.containers.contains(type(owner)) &&
                    name in FormSchema.componentLists(FormSchema.componentTypes.getValue(type(owner)!!))
            }
        }
        else -> node(path) != null
    }

    /** Form fields of the node at [path] (the screen for `""`); null for a list or nothing. */
    fun fields(path: String): List<FormSchema.Field>? = when {
        path.isEmpty() -> FormSchema.screenFields
        path == "data" || path == "values" -> null
        path == NEW_SOURCE -> FormSchema.sourceFields
        path == NEW_VALUE -> FormSchema.valueFields
        isSource(path) -> FormSchema.sourceFields.takeIf { node(path) != null }
        isValue(path) -> FormSchema.valueFields.takeIf { node(path) != null }
        isList(path) || node(path) == null -> null
        else -> type(path)?.let(FormSchema::componentFields)
    }

    /** Current values, defaults written out (components) so the form shows what is really used. */
    fun values(path: String): Map<String, String> {
        val fields = fields(path) ?: return emptyMap()
        if (path.isEmpty()) return FormSchema.values(fields, root)
        if (path == NEW_SOURCE) {
            return FormSchema.values(
                fields,
                FormSchema.sourceWithDefaults(JsonObject(mapOf("url" to JsonPrimitive("")))),
            )
        }
        if (path == NEW_VALUE) {
            return FormSchema.values(fields, FormSchema.valueWithDefaults(JsonObject(emptyMap())))
        }
        if (isSource(path)) return FormSchema.values(fields, FormSchema.sourceWithDefaults(node(path)!!))
        if (isValue(path)) return FormSchema.values(fields, FormSchema.valueWithDefaults(node(path)!!))
        val component = Json.decodeFromJsonElement(Component.serializer(), node(path)!!)
        return FormSchema.values(fields, FormSchema.withDefaults(component))
    }

    /**
     * The node with the form's values; its id/type and component lists are kept from the stored JSON.
     * Renaming a repeat's alias (`as`) renames its uses in the repeat's own lists, like an IDE rename.
     */
    fun rebuild(path: String, parsed: JsonObject): JsonObject {
        val node = node(path)!!
        if (isSource(path) || isValue(path)) return parsed
        val keep = if (path.isEmpty()) {
            // Not in the screen form: id, component lists, data sources and screen values (own nodes).
            listOf("id", "data", "values", "components", "error")
        } else {
            listOf("type") + FormSchema.componentLists(FormSchema.componentTypes.getValue(type(path)!!))
        }
        var kept = keep.mapNotNull { key -> node[key]?.let { key to it } }.toMap()
        if (type(path) == "repeat") {
            val old = (node["as"] as? JsonPrimitive)?.content ?: "item"
            val new = (parsed["as"] as? JsonPrimitive)?.content ?: "item"
            if (old !=
                new
            ) {
                kept =
                    kept.mapValues { (key, value) -> if (key == "type") value else Bindings.rename(value, old, new) }
            }
        }
        return JsonObject(kept + parsed)
    }

    /** What the panel offers for [path]. */
    fun mode(path: String) = when {
        path.isEmpty() -> "screen"
        path == "data" -> "sources"
        path == NEW_SOURCE -> "new-source"
        isSource(path) -> "source"
        path == "values" -> "values"
        path == NEW_VALUE -> "new-value"
        isValue(path) -> "value"
        isList(path) -> "list"
        else -> "component"
    }

    fun isContainer(path: String) = type(path) in Palette.containers

    fun label(path: String) = when (mode(path)) {
        "screen" -> "Screen"
        "sources" -> "Data sources"
        "new-source" -> "Add data source"
        "source" -> "Data source: ${path.removePrefix("data.")}"
        "values" -> "Screen values"
        "new-value" -> "Add screen value"
        "value" -> "Screen value: ${path.removePrefix("values.")}"
        "list" -> "List: ${path.substringAfterLast('.')}"
        else -> type(path).orEmpty()
    }

    companion object {
        const val NEW_SOURCE = "data.__new__"
        const val NEW_VALUE = "values.__new__"
    }
}

private val NEW_ENTRY_NAME = Regex("[A-Za-z][A-Za-z0-9_]{0,63}")

private suspend fun ApplicationCall.editing(screens: ScreenStore): Editing? {
    val id = screenId
    val stored = screens.get(id)
    if (stored == null) {
        respondText("No screen '$id'", status = HttpStatusCode.NotFound)
        return null
    }
    return Editing(stored)
}

private suspend fun ApplicationCall.visualPage(
    screens: ScreenStore,
    editing: Editing,
    node: String,
    value: (String) -> String?,
    visualProblems: List<String>,
    notice: String,
) = respondTemplate(
    "admin/visual.ftl",
    page("${editing.stored.id} · visual") + visualModel(
        screens = screens,
        editing = editing,
        node = node,
        value = value,
        visualProblems = visualProblems,
        notice = notice,
    ),
)

internal fun visualModel(
    screens: ScreenStore,
    editing: Editing,
    node: String = "",
    value: (String) -> String? = editing.values(node)::get,
    visualProblems: List<String> = emptyList(),
    notice: String = "",
    checked: ScreenJson.Checked = ScreenJson.check(editing.json),
    preview: Map<String, String>? = null,
): Map<String, Any> {
    val location = Palette.location(node)
    return mapOf(
        "id" to editing.stored.id,
        "status" to screenStatus(editing.stored),
        "liveEveryMs" to (checked.screen?.live?.everyMs ?: 0),
        "publishedAt" to editing.stored.publishedAt?.toString().orEmpty(),
        "publishedBy" to editing.stored.publishedBy.orEmpty(),
        "json" to editing.json,
        "problems" to checked.problems,
        "warnings" to (checked.screen?.warnings() ?: emptyList()),
        "preview" to (preview ?: emptyMap<String, String>()),
        "history" to historyRows(screens, editing.stored.id),
        "node" to node,
        "nodeLabel" to editing.label(node),
        "mode" to editing.mode(node),
        "isContainer" to editing.isContainer(node),
        "isFirst" to (location?.second == 0),
        "isLast" to (
            location != null &&
                location.second == (ScreenTree.get(editing.root, location.first) as? JsonArray)?.lastIndex
            ),
        "isTopLevel" to (location != null && '.' !in location.first),
        "tree" to ScreenTree.rows(editing.root).map {
            mapOf(
                "path" to it.path,
                "depth" to it.depth,
                "type" to it.type.orEmpty(),
                "label" to it.label,
                "isContainer" to (it.type in Palette.containers),
                "isList" to (
                    it.type == null && it.path != "data" && !it.path.startsWith("data.") &&
                        it.path != "values" && !it.path.startsWith("values.")
                    ),
            )
        },
        "rows" to (
            editing.fields(node)?.let {
                formRows(
                    it,
                    value,
                    (editing.root["values"] as? JsonObject)?.keys?.toList().orEmpty(),
                    collectVisibilityIds(editing.root),
                )
            } ?: emptyList()
            ),
        "palette" to Palette.groups.map { (group, types) -> mapOf("name" to group, "types" to types) },
        "containers" to Palette.containers,
        "panelUrl" to "/admin/screens/${editing.stored.id.urlEncoded()}/visual/panel?node=${node.urlEncoded()}",
        "visualProblems" to visualProblems,
        "notice" to notice,
        "isDraft" to (editing.stored.draftJson != null),
        "newName" to value("__name").orEmpty(),
        "sources" to (editing.root["data"] as? JsonObject).orEmpty().map { (name, source) ->
            mapOf(
                "name" to name,
                "path" to "data.$name",
                "summary" to ((source as? JsonObject)?.get("url") as? JsonPrimitive)?.content.orEmpty(),
            )
        },
        "screenValues" to (editing.root["values"] as? JsonObject).orEmpty().map { (name, value) ->
            val obj = value as? JsonObject
            val min = (obj?.get("min") as? JsonPrimitive)?.content ?: "0"
            val max = (obj?.get("max") as? JsonPrimitive)?.content ?: "100"
            val isAnim = obj?.containsKey("animate") == true
            val badge = if (isAnim) {
                val anim = obj?.get("animate") as? JsonObject
                "animate · ${(anim?.get("mode") as? JsonPrimitive)?.content ?: "pingPong"}"
            } else {
                "$min..$max"
            }
            val summary = if (isAnim) {
                val anim = obj?.get("animate") as? JsonObject
                val dur = (anim?.get("durationMs") as? JsonPrimitive)?.content ?: "2000"
                "${dur}ms · $min..$max"
            } else {
                val def = (obj?.get("default") as? JsonPrimitive)?.content ?: "0"
                "default $def"
            }
            mapOf("name" to name, "path" to "values.$name", "badge" to badge, "summary" to summary)
        },
    )
}

/**
 * The form as a flat list for the template: inputs plus `group`/`end` rows around nested objects;
 * a variant shows the fields of the type currently picked.
 */
internal fun formRows(
    fields: List<FormSchema.Field>,
    value: (String) -> String?,
    screenValues: List<String> = emptyList(),
    visibilityIds: List<String> = emptyList(),
): List<Map<String, Any>> = buildList {
    for (field in fields) {
        val base = mapOf(
            "path" to field.path,
            "label" to field.label,
            "help" to (HELP[field.key] ?: ""),
            "optional" to field.optional,
        )
        when (val kind = field.kind) {
            is FormSchema.Kind.Group -> {
                // Closed unless something in it is set: the modifier alone has 16 fields.
                add(base + mapOf("input" to "group", "open" to FormSchema.filledIn(kind.fields, value)))
                addAll(formRows(kind.fields, value, screenValues, visibilityIds))
                add(mapOf("input" to "end"))
            }
            is FormSchema.Kind.Variant -> {
                val type = value("${field.path}.type").orEmpty()
                add(
                    base + mapOf(
                        "input" to "variant",
                        "value" to type,
                        "options" to kind.variants.keys.toList(),
                        "open" to (type.isNotEmpty() || !field.optional),
                    ),
                )
                kind.variants[type]?.let { addAll(formRows(it, value, screenValues, visibilityIds)) }
                add(mapOf("input" to "end"))
            }
            else -> {
                val current = value(field.path).orEmpty()
                val dynamicChoices = when {
                    field.path == "controls" && screenValues.isNotEmpty() -> screenValues
                    field.key == "target" && visibilityIds.isNotEmpty() -> visibilityIds
                    else -> null
                }?.let { choices ->
                    if (current.isNotEmpty() && current !in choices) listOf(current) + choices else choices
                }
                add(
                    base + mapOf(
                        "input" to when {
                            dynamicChoices != null -> "choice"
                            kind == FormSchema.Kind.Text -> if (field.key.contains("color", ignoreCase = true) ||
                                field.key == "background"
                            ) {
                                "color"
                            } else {
                                "text"
                            }
                            kind is FormSchema.Kind.Number -> "number"
                            kind == FormSchema.Kind.Toggle -> "toggle"
                            kind is FormSchema.Kind.Choice -> "choice"
                            kind == FormSchema.Kind.Dimension -> "dimension"
                            else -> "json"
                        },
                        "value" to current,
                        "lines" to current.lines().size.coerceIn(2, 12),
                        "options" to (
                            dynamicChoices ?: (kind as? FormSchema.Kind.Choice)?.options ?: emptyList<String>()
                            ),
                        "step" to if ((kind as? FormSchema.Kind.Number)?.integer == false) "any" else "1",
                    ),
                )
            }
        }
    }
}

private fun collectVisibilityIds(root: JsonObject): List<String> {
    val ids = linkedSetOf<String>()
    fun walk(el: kotlinx.serialization.json.JsonElement?) {
        when (el) {
            is JsonObject -> {
                val vis = (el["modifier"] as? JsonObject)?.get("visibility") as? JsonObject
                val id = (vis?.get("id") as? JsonPrimitive)?.content?.trim()
                if (!id.isNullOrEmpty()) ids += id
                el.values.forEach(::walk)
            }
            is kotlinx.serialization.json.JsonArray -> el.forEach(::walk)
            else -> Unit
        }
    }
    walk(root["components"])
    return ids.toList()
}

