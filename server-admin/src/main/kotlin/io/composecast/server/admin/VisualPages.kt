/**
 * The visual editor (T-029 C2, ADR 0028): the screen's component tree and a property form for the
 * selected node, generated by [FormSchema]. Saving changes the same stored draft as the JSON editor
 * (`?node=` keeps the selection); only valid screens are saved.
 */
internal fun Route.visualPages(screens: ScreenStore) {
    route("/screens/{id}/visual") {
        get {
            val editing = call.editing(screens) ?: return@get
            val node = call.request.queryParameters["node"].orEmpty()
            val values =
                editing.values(node) ?: return@get call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val notice = if ("saved" in
                call.request.queryParameters
            ) {
                "Saved as a draft. Apps still get the live version."
            } else {
                ""
            }
            call.visualPage(editing, node, values::get, emptyList(), notice)
        }
        post {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            val params = call.receiveParameters()
            val fields =
                editing.fields(node)
                    ?: return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val problems = mutableListOf<String>()
            val parsed = FormSchema.parse(fields, params::get, problems)
            val screen = ScreenTree.set(editing.root, node, editing.rebuild(node, parsed))
            val checked = ScreenJson.check(screen.toString())
            val all = problems + checked.problems
            if (all.isNotEmpty() || checked.screen?.id != editing.stored.id) {
                call.response.status(HttpStatusCode.UnprocessableEntity)
                return@post call.visualPage(
                    editing,
                    node,
                    params::get,
                    all.ifEmpty {
                        listOf("id: must stay '${editing.stored.id}'")
                    },
                    "",
                )
            }
            screens.saveDraft(editing.stored.id, ScreenJson.encode(checked.screen!!))
            call.seeOther("/admin/screens/${editing.stored.id.urlEncoded()}/visual?node=${node.urlEncoded()}&saved")
        }
        // HTMX: re-render the form from what is typed (e.g. another action type picked); saves nothing.
        post("/panel") {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            val params = call.receiveParameters()
            val fields =
                editing.fields(node)
                    ?: return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            call.respondTemplate(
                "admin/_form.ftl",
                mapOf("rows" to formRows(fields, params::get), "canEdit" to true, "panelUrl" to call.panelUrl(node)),
            )
        }
    }
}

/** The screen being edited: the draft if there is one, else the live version. */
private class Editing(val stored: ScreenStore.StoredScreen) {
    val root: JsonObject = Json.parseToJsonElement(stored.draftJson ?: stored.liveJson.orEmpty()) as JsonObject

    fun node(path: String): JsonObject? = ScreenTree.get(root, path) as? JsonObject

    private fun type(path: String) = (node(path)?.get("type") as? JsonPrimitive)?.content

    /** Form fields of the node at [path] (the screen for `""`), or null when there is none. */
    fun fields(path: String): List<FormSchema.Field>? = when {
        path.isEmpty() -> FormSchema.screenFields
        node(path) == null -> null
        else -> type(path)?.let(FormSchema::componentFields)
    }

    /** Current values, defaults written out (components) so the form shows what is really used. */
    fun values(path: String): Map<String, String>? {
        val fields = fields(path) ?: return null
        if (path.isEmpty()) return FormSchema.values(fields, root)
        val component = Json.decodeFromJsonElement(Component.serializer(), node(path)!!)
        return FormSchema.values(fields, FormSchema.withDefaults(component))
    }

    /** The node with the form's values; its id/type and component lists are kept from the stored JSON. */
    fun rebuild(path: String, parsed: JsonObject): JsonObject {
        val node = node(path)!!
        val keep = if (path.isEmpty()) {
            listOf("id", "components", "error")
        } else {
            listOf("type") + FormSchema.componentLists(FormSchema.componentTypes.getValue(type(path)!!))
        }
        return JsonObject(keep.mapNotNull { key -> node[key]?.let { key to it } }.toMap() + parsed)
    }
}

private suspend fun ApplicationCall.editing(screens: ScreenStore): Editing? {
    val id = parameters["id"].orEmpty()
    val stored = screens.get(id)
    if (stored == null) {
        respondText("No screen '$id'", status = HttpStatusCode.NotFound)
        return null
    }
    return Editing(stored)
}

private suspend fun ApplicationCall.visualPage(
    editing: Editing,
    node: String,
    value: (String) -> String?,
    problems: List<String>,
    notice: String,
) {
    val fields = editing.fields(node)!!
    val type = (editing.node(node)?.get("type") as? JsonPrimitive)?.content
    respondTemplate(
        "admin/visual.ftl",
        page("${editing.stored.id} · visual") + mapOf(
            "id" to editing.stored.id,
            "node" to node,
            "nodeLabel" to (type ?: "Screen"),
            "tree" to ScreenTree.rows(editing.root).map {
                mapOf("path" to it.path, "depth" to it.depth, "type" to it.type.orEmpty(), "label" to it.label)
            },
            "rows" to formRows(fields, value),
            "panelUrl" to panelUrl(node),
            "problems" to problems,
            "notice" to notice,
            "isDraft" to (editing.stored.draftJson != null),
        ),
    )
}

/**
 * The form as a flat list for the template: inputs plus `group`/`end` rows around nested objects;
 * a variant shows the fields of the type currently picked.
 */
internal fun formRows(fields: List<FormSchema.Field>, value: (String) -> String?): List<Map<String, Any>> = buildList {
    for (field in fields) {
        val base = mapOf(
            "path" to field.path,
            "label" to field.label,
            "help" to (HELP[field.key] ?: ""),
            "optional" to field.optional,
        )
        when (val kind = field.kind) {
            is FormSchema.Kind.Group -> {
                // Closed unless something in it is set: the modifier alone has 16 fields.
                add(base + mapOf("input" to "group", "open" to FormSchema.filledIn(kind.fields, value)))
                addAll(formRows(kind.fields, value))
                add(mapOf("input" to "end"))
            }
            is FormSchema.Kind.Variant -> {
                val type = value("${field.path}.type").orEmpty()
                add(
                    base + mapOf(
                        "input" to "variant",
                        "value" to type,
                        "options" to kind.variants.keys.toList(),
                        "open" to (type.isNotEmpty() || !field.optional),
                    ),
                )
                kind.variants[type]?.let { addAll(formRows(it, value)) }
                add(mapOf("input" to "end"))
            }
            else -> add(
                base + mapOf(
                    "input" to when (kind) {
                        FormSchema.Kind.Text -> if (field.key.contains("color", ignoreCase = true) ||
                            field.key == "background"
                        ) {
                            "color"
                        } else {
                            "text"
                        }
                        is FormSchema.Kind.Number -> "number"
                        FormSchema.Kind.Toggle -> "toggle"
                        is FormSchema.Kind.Choice -> "choice"
                        FormSchema.Kind.Dimension -> "dimension"
                        else -> "json"
                    },
                    "value" to value(field.path).orEmpty(),
                    "lines" to (value(field.path).orEmpty().lines().size.coerceIn(2, 12)),
                    "options" to ((kind as? FormSchema.Kind.Choice)?.options ?: emptyList<String>()),
                    "step" to if ((kind as? FormSchema.Kind.Number)?.integer == false) "any" else "1",
                ),
            )
        }
    }
}

/** Short help by field name; the rest is self-explaining or in docs/screen-json-format.md. */
private val HELP = mapOf(
    "padding" to "dp on each side",
    "width" to "dp, fill or wrap",
    "height" to "dp, fill or wrap",
    "weight" to "share of the free space in a row/column",
    "spacing" to "dp between children",
    "cornerRadius" to "dp",
    "url" to "https://… (may use {{bindings}})",
    "text" to "may use {{bindings}}",
    "items" to "a data path (e.g. meteo.daily.time) or {\"name\": \"path\", …}",
    "params" to "JSON object, e.g. {\"id\": \"{{item.id}}\"}",
    "data" to "JSON: data sources by name (docs/screen-json-format.md)",
    "lookups" to "JSON: value tables for the lookup filter",
    "fillFraction" to "0–1 of the parent's width",
)

/** Where the form re-renders itself (HTMX, variant changes). */
private fun ApplicationCall.panelUrl(node: String) =
    "/admin/screens/${parameters["id"].orEmpty().urlEncoded()}/visual/panel?node=${node.urlEncoded()}"

private fun String.urlEncoded() = URLEncoder.encode(this, Charsets.UTF_8).replace("+", "%20")
