/**
 * The visual editor (T-029 C2, C3; ADR 0028): the screen's component tree, a property form for the
 * selected node generated by [FormSchema], and the palette's structural edits ([Palette]). Every
 * change is checked as a whole screen and saved as the same draft the JSON editor shows; `?node=`
 * is the selection (a component, `""` for the screen, or a list such as `components.2.empty`).
 */
internal fun Route.visualPages(screens: ScreenStore) {
    route("/screens/{id}/visual") {
        get {
            val editing = call.editing(screens) ?: return@get
            val node = call.request.queryParameters["node"].orEmpty()
            if (!editing.exists(node)) return@get call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val saved = "saved" in call.request.queryParameters
            val notice = if (saved) "Saved as a draft. Apps still get the live version." else ""
            call.visualPage(editing, node, editing.values(node)::get, emptyList(), notice)
        }
        post {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            val fields =
                editing.fields(node)
                    ?: return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val params = call.receiveParameters()
            val problems = mutableListOf<String>()
            val parsed = FormSchema.parse(fields, params::get, problems)
            val screen = ScreenTree.set(editing.root, node, editing.rebuild(node, parsed))
            call.saveOrShow(screens, editing, screen, node, problems) { params[it] }
        }
        // C3: add, delete, duplicate, move, nest, wrap — form fields `op` and `type`.
        post("/edit") {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            if (!editing.exists(node)) return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val params = call.receiveParameters()
            val type = params["type"].orEmpty()
            val root = editing.root
            val result = try {
                when (params["op"]) {
                    "add-after" -> requireNotNull(Palette.location(node)) { "select a component first" }
                        .let { (list, index) -> Palette.add(root, list, index + 1, type) }
                    "add-inside" -> Palette.add(
                        root,
                        "$node.${requireNotNull(Palette.firstList(root, node)) {
                            "not a container"
                        }}",
                        null,
                        type,
                    )
                    "add-end" -> Palette.add(root, node.ifEmpty { "components" }, null, type)
                    "up" -> Palette.move(root, node, -1)
                    "down" -> Palette.move(root, node, 1)
                    "into-previous" -> Palette.intoPrevious(root, node)
                    "out" -> Palette.outOfParent(root, node)
                    "duplicate" -> Palette.duplicate(root, node)
                    "delete" -> Palette.delete(root, node)
                    "wrap" -> Palette.wrap(root, node, type)
                    else -> throw IllegalArgumentException("unknown operation '${params["op"]}'")
                }
            } catch (e: IllegalArgumentException) {
                call.response.status(HttpStatusCode.UnprocessableEntity)
                return@post call.visualPage(
                    editing,
                    node,
                    editing.values(node)::get,
                    listOf(e.message ?: "not possible"),
                    "",
                )
            }
            call.saveOrShow(screens, editing, result.screen, result.select, emptyList()) { editing.values(node)[it] }
        }
        // HTMX: re-render the form from what is typed (e.g. another action type picked); saves nothing.
        post("/panel") {
            val editing = call.editing(screens) ?: return@post
            val node = call.request.queryParameters["node"].orEmpty()
            val fields =
                editing.fields(node)
                    ?: return@post call.respondText("No node '$node'", status = HttpStatusCode.NotFound)
            val params = call.receiveParameters()
            call.respondTemplate(
                "admin/_form.ftl",
                mapOf("rows" to formRows(fields, params::get), "canEdit" to true, "panelUrl" to call.panelUrl(node)),
            )
        }
    }
}

/**
 * Saves [screen] as the draft when it is valid and keeps its id, then selects [select]; otherwise
 * shows the page again (at the old selection, with [value] in the form) with every problem.
 */
private suspend fun ApplicationCall.saveOrShow(
    screens: ScreenStore,
    editing: Editing,
    screen: JsonObject,
    select: String,
    problems: List<String>,
    value: (String) -> String?,
) {
    val checked = ScreenJson.check(screen.toString())
    val valid = checked.screen
    val all = problems + checked.problems +
        listOfNotNull("id: must stay '${editing.stored.id}'".takeIf { valid != null && valid.id != editing.stored.id })
    val node = request.queryParameters["node"].orEmpty()
    if (all.isNotEmpty() || valid == null) {
        response.status(HttpStatusCode.UnprocessableEntity)
        return visualPage(editing, node, value, all, "")
    }
    screens.saveDraft(editing.stored.id, ScreenJson.encode(valid))
    seeOther("/admin/screens/${editing.stored.id.urlEncoded()}/visual?node=${select.urlEncoded()}&saved")
}

/** The screen being edited: the draft if there is one, else the live version. */
private class Editing(val stored: ScreenStore.StoredScreen) {
    val root: JsonObject = Json.parseToJsonElement(stored.draftJson ?: stored.liveJson.orEmpty()) as JsonObject

    fun node(path: String): JsonObject? = ScreenTree.get(root, path) as? JsonObject

    private fun type(path: String) = (node(path)?.get("type") as? JsonPrimitive)?.content

    /** A component list path (`components`, `components.2.empty`): its last segment is a name. */
    fun isList(path: String) = path.isNotEmpty() && path.substringAfterLast('.').toIntOrNull() == null

    /** The selection exists: the screen, a component, or a component list of the screen or a component. */
    fun exists(path: String): Boolean = when {
        path.isEmpty() -> true
        isList(path) -> {
            val owner = if ('.' in path) path.substringBeforeLast('.') else ""
            val name = path.substringAfterLast('.')
            if (owner.isEmpty()) {
                name in setOf("components", "error")
            } else {
                Palette.containers.contains(type(owner)) &&
                    name in FormSchema.componentLists(FormSchema.componentTypes.getValue(type(owner)!!))
            }
        }
        else -> node(path) != null
    }

    /** Form fields of the node at [path] (the screen for `""`); null for a list or nothing. */
    fun fields(path: String): List<FormSchema.Field>? = when {
        path.isEmpty() -> FormSchema.screenFields
        isList(path) || node(path) == null -> null
        else -> type(path)?.let(FormSchema::componentFields)
    }

    /** Current values, defaults written out (components) so the form shows what is really used. */
    fun values(path: String): Map<String, String> {
        val fields = fields(path) ?: return emptyMap()
        if (path.isEmpty()) return FormSchema.values(fields, root)
        val component = Json.decodeFromJsonElement(Component.serializer(), node(path)!!)
        return FormSchema.values(fields, FormSchema.withDefaults(component))
    }

    /**
     * The node with the form's values; its id/type and component lists are kept from the stored JSON.
     * Renaming a repeat's alias (`as`) renames its uses in the repeat's own lists, like an IDE rename.
     */
    fun rebuild(path: String, parsed: JsonObject): JsonObject {
        val node = node(path)!!
        val keep = if (path.isEmpty()) {
            listOf("id", "components", "error")
        } else {
            listOf("type") + FormSchema.componentLists(FormSchema.componentTypes.getValue(type(path)!!))
        }
        var kept = keep.mapNotNull { key -> node[key]?.let { key to it } }.toMap()
        if (type(path) == "repeat") {
            val old = (node["as"] as? JsonPrimitive)?.content ?: "item"
            val new = (parsed["as"] as? JsonPrimitive)?.content ?: "item"
            if (old !=
                new
            ) {
                kept =
                    kept.mapValues { (key, value) -> if (key == "type") value else Bindings.rename(value, old, new) }
            }
        }
        return JsonObject(kept + parsed)
    }

    /** What the panel offers for [path]: `screen`, `list` or `component`. */
    fun mode(path: String) = when {
        path.isEmpty() -> "screen"
        isList(path) -> "list"
        else -> "component"
    }

    fun isContainer(path: String) = type(path) in Palette.containers

    fun label(path: String) = when (mode(path)) {
        "screen" -> "Screen"
        "list" -> "List: ${path.substringAfterLast('.')}"
        else -> type(path).orEmpty()
    }
}

private suspend fun ApplicationCall.editing(screens: ScreenStore): Editing? {
    val id = parameters["id"].orEmpty()
    val stored = screens.get(id)
    if (stored == null) {
        respondText("No screen '$id'", status = HttpStatusCode.NotFound)
        return null
    }
    return Editing(stored)
}

private suspend fun ApplicationCall.visualPage(
    editing: Editing,
    node: String,
    value: (String) -> String?,
    problems: List<String>,
    notice: String,
) {
    val location = Palette.location(node)
    respondTemplate(
        "admin/visual.ftl",
        page("${editing.stored.id} · visual") + mapOf(
            "id" to editing.stored.id,
            "node" to node,
            "nodeLabel" to editing.label(node),
            "mode" to editing.mode(node),
            "isContainer" to editing.isContainer(node),
            "isFirst" to (location?.second == 0),
            "isLast" to
                (
                    location != null &&
                        location.second == (ScreenTree.get(editing.root, location.first) as? JsonArray)?.lastIndex
                    ),
            "isTopLevel" to (location != null && '.' !in location.first),
            "tree" to ScreenTree.rows(editing.root).map {
                mapOf("path" to it.path, "depth" to it.depth, "type" to it.type.orEmpty(), "label" to it.label)
            },
            "rows" to (editing.fields(node)?.let { formRows(it, value) } ?: emptyList()),
            "palette" to Palette.groups.map { (group, types) -> mapOf("name" to group, "types" to types) },
            "containers" to Palette.containers,
            "panelUrl" to panelUrl(node),
            "problems" to problems,
            "notice" to notice,
            "isDraft" to (editing.stored.draftJson != null),
        ),
    )
}

/**
 * The form as a flat list for the template: inputs plus `group`/`end` rows around nested objects;
 * a variant shows the fields of the type currently picked.
 */
internal fun formRows(fields: List<FormSchema.Field>, value: (String) -> String?): List<Map<String, Any>> = buildList {
    for (field in fields) {
        val base = mapOf(
            "path" to field.path,
            "label" to field.label,
            "help" to (HELP[field.key] ?: ""),
            "optional" to field.optional,
        )
        when (val kind = field.kind) {
            is FormSchema.Kind.Group -> {
                // Closed unless something in it is set: the modifier alone has 16 fields.
                add(base + mapOf("input" to "group", "open" to FormSchema.filledIn(kind.fields, value)))
                addAll(formRows(kind.fields, value))
                add(mapOf("input" to "end"))
            }
            is FormSchema.Kind.Variant -> {
                val type = value("${field.path}.type").orEmpty()
                add(
                    base + mapOf(
                        "input" to "variant",
                        "value" to type,
                        "options" to kind.variants.keys.toList(),
                        "open" to (type.isNotEmpty() || !field.optional),
                    ),
                )
                kind.variants[type]?.let { addAll(formRows(it, value)) }
                add(mapOf("input" to "end"))
            }
            else -> add(
                base + mapOf(
                    "input" to when (kind) {
                        FormSchema.Kind.Text -> if (field.key.contains("color", ignoreCase = true) ||
                            field.key == "background"
                        ) {
                            "color"
                        } else {
                            "text"
                        }
                        is FormSchema.Kind.Number -> "number"
                        FormSchema.Kind.Toggle -> "toggle"
                        is FormSchema.Kind.Choice -> "choice"
                        FormSchema.Kind.Dimension -> "dimension"
                        else -> "json"
                    },
                    "value" to value(field.path).orEmpty(),
                    "lines" to (value(field.path).orEmpty().lines().size.coerceIn(2, 12)),
                    "options" to ((kind as? FormSchema.Kind.Choice)?.options ?: emptyList<String>()),
                    "step" to if ((kind as? FormSchema.Kind.Number)?.integer == false) "any" else "1",
                ),
            )
        }
    }
}

/** Short help by field name; the rest is self-explaining or in docs/screen-json-format.md. */
private val HELP = mapOf(
    "padding" to "dp on each side",
    "width" to "dp, fill or wrap",
    "height" to "dp, fill or wrap",
    "weight" to "share of the free space in a row/column",
    "spacing" to "dp between children",
    "cornerRadius" to "dp",
    "url" to "https://… (may use {{bindings}})",
    "text" to "may use {{bindings}}",
    "items" to "a data path (e.g. meteo.daily.time) or {\"name\": \"path\", …}",
    "params" to "JSON object, e.g. {\"id\": \"{{item.id}}\"}",
    "data" to "JSON: data sources by name (docs/screen-json-format.md)",
    "lookups" to "JSON: value tables for the lookup filter",
    "fillFraction" to "0–1 of the parent's width",
)

/** Where the form re-renders itself (HTMX, variant changes). */
private fun ApplicationCall.panelUrl(node: String) =
    "/admin/screens/${parameters["id"].orEmpty().urlEncoded()}/visual/panel?node=${node.urlEncoded()}"

private fun String.urlEncoded() = URLEncoder.encode(this, Charsets.UTF_8).replace("+", "%20")
