#!/usr/bin/env bash
# Generates docs/STATUS.md (project overview) from the sources of truth, so it cannot go stale:
# the task queue (docs/tasks/README.md), README roadmap, ADR index and docs/history.md.
#   ./scripts/gen-status.sh          rewrite docs/STATUS.md
#   ./scripts/gen-status.sh --check  exit 1 if it is out of date (run by check-docs.sh / CI)
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 - "${1:-}" <<'PY'
import pathlib, re, sys

root = pathlib.Path(".")
out = root / "docs" / "STATUS.md"

def table(text):
    """First Markdown table in text → list of cell lists (header and separator skipped)."""
    rows = [l for l in text.splitlines() if l.startswith("|")]
    return [[c.strip() for c in r.strip("|").split("|")] for r in rows[2:]]

tasks = table((root / "docs/tasks/README.md").read_text())
tasks = [[re.sub(r"\]\((T-[^)]+)\)", r"](tasks/\1)", c) for c in row] for row in tasks]
ready = [r for r in tasks if r[2] == "ready"]
waiting = [r for r in tasks if r[2].startswith(("needs design", "blocked"))]

etaps = []
section = None
for line in (root / "README.md").read_text().splitlines():
    if line.startswith("### Etap"):
        section = [re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", line[4:]), 0, 0]
        etaps.append(section)
    elif line.startswith("## ") and section:
        section = None
    elif section and re.match(r"- \[[ x]\]", line):
        section[2] += 1
        section[1] += line.startswith("- [x]")

adrs = table((root / "docs/decisions/README.md").read_text())
proposed = [a for a in adrs if a[2] == "Proposed"]

history = re.findall(r"^\d+\. \*\*(.+?)\*\*", (root / "docs/history.md").read_text(), re.M)

lines = [
    "# compose-cast — project status",
    "",
    "_Generated by `scripts/gen-status.sh` from the task queue, README roadmap, ADR index and",
    "history — do not edit by hand (`check-docs.sh` fails when it is stale). Details: follow the links._",
    "",
    "## Next",
    "",
]
lines += [f"- **{r[0]}** ({r[1]}) — the `ready` task." for r in ready] or ["- No `ready` task: specify one."]
lines += ["", "## Task queue (priority order)", "", "| Task | Roadmap | Status |", "|---|---|---|"]
lines += [f"| {' | '.join(r)} |" for r in tasks]
lines += ["", "## Roadmap", "", "| Etap | Done |", "|---|---|"]
lines += [f"| {name} | {done}/{total} |" for name, done, total in etaps]
lines += ["", "## Waiting for a decision or design", ""]
lines += [f"- {r[0]}: {r[2]}" for r in waiting]
lines += [f"- ADR {a[0].replace('](', '](decisions/')}: {a[1]} (Proposed)" for a in proposed]
lines += ["", "## Recent work (docs/history.md)", ""]
lines += [f"- {h}" for h in history[-6:][::-1]]
text = "\n".join(lines) + "\n"

if sys.argv[1] == "--check":
    if not out.is_file() or out.read_text() != text:
        print("docs/STATUS.md is out of date: run ./scripts/gen-status.sh")
        sys.exit(1)
else:
    out.write_text(text)
    print(f"wrote {out}")
PY
